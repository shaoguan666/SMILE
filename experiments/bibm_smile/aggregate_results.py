"""Aggregate SMART/SMILE training logs into CSV and LaTeX tables.

The script does not fabricate missing results. A dataset/variant/seed row is
marked missing if no training.log is found or if the expected metrics cannot be
parsed from the final test block.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
from collections import defaultdict
from pathlib import Path
from statistics import mean, pstdev


HERE = Path(__file__).resolve().parent
SMART_DIR = HERE.parents[1]
DEFAULT_CONFIG = HERE / "configs" / "bibm_smile_experiments.json"
DEFAULT_EXPORT_ROOT = SMART_DIR / "export" / "bibm_audit_fixed"
DEFAULT_OUT = HERE / "results" / "bibm_audit_fixed"

BINARY_DATASETS = {"c12", "c19", "mimic_mortality", "mimic_decompensation"}
MULTI_DATASETS = {"mimic_phenotyping", "mimic_lengthofstay"}

PATTERNS = {
    "auroc": re.compile(r"AUC of ROC = ([0-9.]+)"),
    "auprc": re.compile(r"AUC of PRC = ([0-9.]+)"),
    "minpse": re.compile(r"min\(\+P, Se\) = ([0-9.]+)"),
    "f1": re.compile(r"f1_score = ([0-9.]+)"),
    "auc_micro": re.compile(r"auc_micro = ([0-9.]+)"),
    "auc_macro": re.compile(r"auc_macro = ([0-9.]+)"),
    "auc_weighted": re.compile(r"auc_weighted = ([0-9.]+)"),
}


def load_config(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def candidate_logs(export_root: Path, dataset: str, variant: str, seed: int) -> list[Path]:
    rel = Path(dataset) / variant / f"seed_{seed}" / "training.log"
    return [export_root / rel]


def choose_log(paths: list[Path]) -> Path | None:
    existing = [p for p in paths if p.exists()]
    if not existing:
        return None
    return max(existing, key=lambda p: p.stat().st_mtime)


def parse_log(path: Path, dataset: str) -> dict[str, float]:
    text = path.read_text(encoding="utf-8", errors="replace")
    metrics: dict[str, float] = {}
    keys = ["auroc", "auprc", "minpse", "f1"] if dataset in BINARY_DATASETS else [
        "auc_micro", "auc_macro", "auc_weighted"
    ]
    for key in keys:
        matches = PATTERNS[key].findall(text)
        if matches:
            metrics[key] = float(matches[-1]) * 100.0
    eval_path = path.with_name("eval_results.json")
    if eval_path.exists():
        try:
            payload = json.loads(eval_path.read_text(encoding="utf-8"))
            frozen = payload.get("validation_threshold_metrics") or {}
            if dataset in BINARY_DATASETS and "f1" in frozen:
                metrics["f1"] = float(frozen["f1"]) * 100.0
        except Exception:
            pass
    return metrics


def fmt_metric(values: list[float]) -> str:
    if not values:
        return "--"
    if len(values) == 1:
        return f"{values[0]:.2f}"
    return f"{mean(values):.2f}\\sm{pstdev(values):.2f}"


def write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = sorted({k for row in rows for k in row.keys()})
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def aggregate(rows: list[dict]) -> list[dict]:
    grouped: dict[tuple[str, str, str, str], list[float]] = defaultdict(list)
    for row in rows:
        if row.get("status") != "ok":
            continue
        grouped[(row["dataset"], row["variant_name"], row["variant"], row["metric"])].append(float(row["value"]))
    out = []
    for (dataset, name, variant, metric), vals in sorted(grouped.items()):
        out.append({
            "dataset": dataset,
            "variant_name": name,
            "variant": variant,
            "metric": metric,
            "n": len(vals),
            "mean": mean(vals),
        "std": pstdev(vals) if len(vals) > 1 else 0.0,
            "formatted": fmt_metric(vals),
        })
    return out


def make_ablation_table(summary: list[dict], out_path: Path) -> None:
    lookup = {(r["dataset"], r["variant_name"], r["metric"]): r["formatted"] for r in summary}
    rows = [
        "Backbone",
        "SMILE-Full",
        "SMILE w/o Density",
        "SMILE w/o CoMiss Bias",
        "SMILE w/o Time-Affine",
    ]
    ds = ["c12", "c19", "mimic_mortality", "mimic_decompensation"]
    lines = [
        "% Auto-generated by SMART/experiments/bibm_smile/aggregate_results.py",
        "\\begin{table*}[htbp]",
        "\\centering",
        "\\caption{Ablation table template generated from available logs. Missing entries are shown as -- and must not be interpreted as results.}",
        "\\label{tab:ablation_generated}",
        "\\scriptsize",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{l" + "cc" * len(ds) + "}",
        "\\toprule",
        "\\textbf{Configuration} & " + " & ".join([f"\\multicolumn{{2}}{{c}}{{\\textbf{{{d}}}}}" for d in ds]) + " \\\\",
        " & " + " & ".join(["AUPRC & F1" for _ in ds]) + " \\\\",
        "\\midrule",
    ]
    for name in rows:
        vals = []
        for d in ds:
            vals.append(lookup.get((d, name, "auprc"), "--"))
            vals.append(lookup.get((d, name, "f1"), "--"))
        lines.append(name + " & " + " & ".join(vals) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "}", "\\end{table*}", ""]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--export-root", type=Path, default=DEFAULT_EXPORT_ROOT)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    cfg = load_config(args.config)
    rows = []
    for name, variant in cfg["implemented_variants"].items():
        for dataset in cfg["datasets"]:
            for seed in cfg["seeds"]:
                log_path = choose_log(candidate_logs(args.export_root, dataset, variant, seed))
                base = {
                    "dataset": dataset,
                    "variant_name": name,
                    "variant": variant,
                    "seed": seed,
                    "log_path": str(log_path) if log_path else "",
                }
                if log_path is None:
                    rows.append({**base, "metric": "", "value": "", "status": "missing_log"})
                    continue
                metrics = parse_log(log_path, dataset)
                if not metrics:
                    rows.append({**base, "metric": "", "value": "", "status": "missing_metrics"})
                    continue
                for metric, value in metrics.items():
                    rows.append({**base, "metric": metric, "value": value, "status": "ok"})

    summary = aggregate(rows)
    write_csv(args.out_dir / "bibm_results_long.csv", rows)
    write_csv(args.out_dir / "bibm_results_summary.csv", summary)
    make_ablation_table(summary, args.out_dir / "latex" / "ablation_generated.tex")
    print(f"Wrote {args.out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
